/* Derive src/vendor/98.scoped.css from the 98.css package.
   Run: node scripts/vendor-98css.mjs

   Two things have to change before 98.css can be used here:

   1. It ships "Pixelated MS Sans Serif" as woff/woff2. Those are
      Microsoft fonts, which the project rules forbid, and importing the
      stylesheet as-is makes Vite emit the binaries into dist/. The
      @font-face blocks are dropped and the stack falls back to the
      site's own --font.
   2. It styles bare `body`, `h1`-`h4`, `button`, `input`, `select`,
      `table` and `textarea`, which would stomp the existing desktop
      chrome. Every rule is therefore scoped under `.ui98`, so the kit
      only applies inside the login screen on the CRT.

   3. Its `.window` and `.window-body` class names are already taken by
      the desktop's own chrome (and `main.js` drives every `.window` on
      the page through the window manager). They are renamed to
      `.win98` / `.win98-body`, so the login dialog is not picked up as
      a draggable desktop window.

   Everything else is left alone — the icons are all inline data: SVGs
   drawn by the 98.css author, not Microsoft artwork.
*/
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'node_modules/98.css/dist/98.css';
const OUT = 'src/vendor/98.scoped.css';
const SCOPE = '.ui98';

let css = readFileSync(SRC, 'utf8');

/* 0. Strip comments, so the banner cannot glue itself onto the first
   selector when the sheet is re-scoped. */
css = css.replace(/\/\*[\s\S]*?\*\//g, '');

/* 1. No Microsoft fonts. */
css = css.replace(/@font-face\{[^}]*\}/g, '');
css = css.replace(/font-family:"Pixelated MS Sans Serif",Arial/g, 'font-family:var(--font)');
css = css.replace(/font-family:"Pixelated MS Sans Serif"/g, 'font-family:var(--font)');

/* 2. Scope. Walk the minified sheet tracking brace depth, prefixing the
   selector of every rule that would otherwise be global. @media is the
   only at-rule left, so its block is descended into rather than
   prefixed. */
function scope(body) {
  let out = '';
  let sel = '';
  let i = 0;
  while (i < body.length) {
    const ch = body[i];
    if (ch === '{') {
      const head = sel.trim();
      sel = '';
      const end = matchBrace(body, i);
      const inner = body.slice(i + 1, end);
      if (head.startsWith('@media')) {
        out += `${head}{${scope(inner)}}`;
      } else if (head) {
        /* `body` prefixes away to nothing — drop the rule rather than
           emit a block with no selector. */
        const sels = prefix(head);
        if (sels) out += `${sels}{${inner}}`;
      }
      i = end + 1;
    } else {
      sel += ch;
      i++;
    }
  }
  return out;
}

function matchBrace(s, open) {
  let depth = 0;
  for (let i = open; i < s.length; i++) {
    if (s[i] === '{') depth++;
    else if (s[i] === '}' && --depth === 0) return i;
  }
  throw new Error('unbalanced braces in ' + SRC);
}

/* `body` would become `.ui98 body`, which can never match — drop it, we
   do not want its colour and font on the login screen anyway. */
function prefix(head) {
  return head
    .split(',')
    .map(s => s.trim())
    .filter(s => s && s !== 'body' && !s.startsWith('body '))
    .map(s => (s.startsWith(':root') ? s.replace(':root', SCOPE) : `${SCOPE} ${s}`))
    .join(',');
}

let out = scope(css).trim();

/* 3. Rename the two classes the desktop chrome already owns. Longest
   first: \b matches inside `.window-body` too. */
out = out
  .replace(/\.window-body\b/g, '.win98-body')
  .replace(/\.window\b/g, '.win98');

const banner = `/* 98.css v${JSON.parse(readFileSync('node_modules/98.css/package.json', 'utf8')).version} by Jordan Scales — MIT.
   https://github.com/jdan/98.css
   GENERATED by scripts/vendor-98css.mjs — do not edit by hand.
   Scoped to ${SCOPE}; the bundled MS Sans Serif webfonts are stripped. */
`;

writeFileSync(OUT, banner + out + '\n');
console.log(`wrote ${OUT}`);
